const STAGE_LABELS = {
  amphitheater: 'Amphitheater Stage',
  pyramid: 'Pyramid Stage',
  waterfront: 'Waterfront Stage',
  'jazz-hall': 'Detroit Jazz Hall',
} as const;

type StageId = keyof typeof STAGE_LABELS;

function performance(
  id: string,
  title: string,
  startsAt: string,
  stageId: StageId,
  details?: string,
): EventScheduleItem {
  return {
    id,
    title,
    startsAt,
    venue: STAGE_LABELS[stageId],
    category: 'music',
    tags: ['music', stageId],
    ...(details ? { details } : {}),
    sourceIds: [OFFICIAL_LINEUP_SOURCE_ID],
    confidence: 'verified',
  };
}

