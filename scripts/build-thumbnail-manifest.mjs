import { readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const sharp = require('sharp');

const entries = [
  { eventId: 'romeo-peach', requestedSlug: 'romeo-peach-festival', source: 'public/event-media/romeo/romeo-peach-memory-bg-v1.webp' },
  { eventId: 'goodells-fair', requestedSlug: 'goodells-fair', source: 'public/event-media/generated/goodells-fair-thumb.webp' },
  { eventId: 'mackinac-lilac', requestedSlug: 'mackinac-lilac', source: 'public/event-media/generated/mackinac-lilac-thumb.webp' },
  { eventId: 'traverse-city-cherry', requestedSlug: 'traverse-city-cherry', source: 'public/event-media/generated/traverse-city-cherry-thumb.webp' },
  { eventId: 'holland-tulip-time', requestedSlug: 'holland-tulip-time', source: 'public/event-media/generated/holland-tulip-time-thumb.webp' },
  { eventId: 'black-river-tattoo', requestedSlug: 'black-river-tattoo', source: 'public/event-media/generated/black-river-tattoo-thumb.webp' },
  { eventId: 'detroit-jazz', requestedSlug: 'detroit-jazz', source: 'public/event-media/generated/detroit-jazz-thumb.webp' },
];

const out = ['// Small-card Celebration Atlas thumbnail manifest. Generated by scripts/build-thumbnail-manifest.mjs.', '// Keep entries small; this manifest is only for initial Michigan compact card review.', '', 'export type ManifestEventThumbnail = {', '  eventId: string;', '  requestedSlug: string;', '  dataUri: `data:image/webp;base64,${string}`;', '  byteLength: number;', '  source: \'manifest\';', '  status: \'embedded-preview\';', '};', '', 'export const MANIFEST_EVENT_THUMBNAILS: Record<string, ManifestEventThumbnail> = {'];
let total = 0;
for (const entry of entries) {
  const input = await readFile(path.join(process.cwd(), entry.source));
  const buffer = await sharp(input).resize({ width: 128, height: 72, fit: 'cover' }).webp({ quality: 48, effort: 6 }).toBuffer();
  total += buffer.length;
  out.push(`  '${entry.eventId}': {`);
  out.push(`    eventId: '${entry.eventId}',`);
  out.push(`    requestedSlug: '${entry.requestedSlug}',`);
  out.push(`    dataUri: 'data:image/webp;base64,${buffer.toString('base64')}',`);
  out.push(`    byteLength: ${buffer.length},`);
  out.push("    source: 'manifest',");
  out.push("    status: 'embedded-preview',");
  out.push('  },');
}
out.push('};', '');
out.push(`export const MANIFEST_EVENT_THUMBNAIL_TOTAL_BYTES = ${total};`, '');
out.push('export function getManifestEventThumbnail(eventId: string): ManifestEventThumbnail | undefined {', '  return MANIFEST_EVENT_THUMBNAILS[eventId];', '}', '');
await mkdir(path.join(process.cwd(), 'data'), { recursive: true });
await writeFile(path.join(process.cwd(), 'data', 'eventThumbnailManifest.ts'), out.join('\n'));
console.log(`Wrote ${entries.length} manifest thumbnails (${total} bytes before base64).`);
